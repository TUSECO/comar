use crate::error::{ComarError, Result};
use std::path::Path;
use std::process::Command;
use zvariant::{OwnedValue, Value};

pub struct NetworkStack;

impl super::ServiceHandler for NetworkStack {
    fn handle(
        &self,
        method: &str,
        args: &[OwnedValue],
        lang: &str,
    ) -> Result<Vec<OwnedValue>> {
        match method {
            "getHostName" => get_host_name(),
            "setHostName" => set_host_name(args, lang),
            "getNameServers" => get_name_servers(),
            "setNameServers" => set_name_servers(args, lang),
            "useNameServers" => use_name_servers(args, lang),
            "registerNameServers" => register_name_servers(args, lang),
            "unregisterNameServers" => unregister_name_servers(args, lang),
            "flushNameCache" => Ok(vec![]),
            _ => Err(ComarError::Missing(format!(
                "Network.Stack: unknown method '{}'",
                method
            ))),
        }
    }
}

const HOSTNAME_PATH: &str = "/etc/env.d/01hostname";
const HOSTS_PATH: &str = "/etc/hosts";
const RESOLV_USER: &str = "/etc/resolv.default.conf";
const RESOLV_LUPUS: &str = "/usr/share/baselayout/resolv.conf";
const MAX_SERVERS: usize = 3;

fn get_host_name() -> Result<Vec<OwnedValue>> {
    let output = Command::new("/usr/bin/hostname")
        .output()
        .map_err(|e| ComarError::Script(format!("hostname: {}", e)))?;
    let name = String::from_utf8_lossy(&output.stdout).trim().to_string();
    Ok(vec![OwnedValue::try_from(Value::from(name)).unwrap()])
}

fn set_host_name(args: &[OwnedValue], _lang: &str) -> Result<Vec<OwnedValue>> {
    let hostname = arg_to_string(args, 0, "")?;
    if hostname.is_empty() {
        return Ok(vec![]);
    }

    let valid = |c: char| c.is_ascii_alphanumeric() || c == '.' || c == '_' || c == '-';
    let invalid: String = hostname.chars().filter(|c| !valid(*c)).collect();
    if !invalid.is_empty() {
        return Err(ComarError::Invalid(format!(
            "Hostname contains invalid characters: '{}'",
            invalid
        )));
    }

    let content = if Path::new(HOSTNAME_PATH).exists() {
        let data = std::fs::read_to_string(HOSTNAME_PATH)
            .map_err(|e| ComarError::Io(e))?;
        let re = regex::Regex::new(r#"HOSTNAME="(.*)""#).unwrap();
        re.replace(&data, format!(r#"HOSTNAME="{}""#, hostname))
            .to_string()
    } else {
        format!("HOSTNAME=\"{}\"\n", hostname)
    };
    std::fs::write(HOSTNAME_PATH, content.as_bytes())
        .map_err(|e| ComarError::Io(e))?;

    let hosts_content = std::fs::read_to_string(HOSTS_PATH)
        .map_err(|e| ComarError::Io(e))?;
    let mut found = false;
    let new_hosts: String = hosts_content
        .lines()
        .map(|line| {
            if line.starts_with("127.0.0.1") {
                found = true;
                format!("127.0.0.1 localhost {}\n", hostname)
            } else {
                format!("{}\n", line)
            }
        })
        .collect::<Vec<_>>()
        .concat();
    let new_hosts = if !found {
        format!("{}127.0.0.1 localhost {}\n", new_hosts, hostname)
    } else {
        new_hosts
    };
    std::fs::write(HOSTS_PATH, new_hosts.as_bytes())
        .map_err(|e| ComarError::Io(e))?;

    let _ = Command::new("/sbin/update-environment").output();

    Ok(vec![])
}

fn get_name_servers() -> Result<Vec<OwnedValue>> {
    let servers = read_nameservers(RESOLV_USER);
    Ok(vec![OwnedValue::try_from(Value::from(servers)).unwrap()])
}

fn set_name_servers(args: &[OwnedValue], _lang: &str) -> Result<Vec<OwnedValue>> {
    let servers: Vec<String> = arg_to_array(args, 0);
    let searchdomain = arg_to_string(args, 1, "")?;

    let mut content = String::from("# Default DNS settings\n#\n");
    for s in &servers {
        content.push_str(&format!("nameserver {}\n", s));
    }
    if !searchdomain.is_empty() {
        content.push_str(&format!("searchdomain {}\n", searchdomain));
    }
    std::fs::write(RESOLV_USER, content.as_bytes())
        .map_err(|e| ComarError::Io(e))?;
    Ok(vec![])
}

fn use_name_servers(args: &[OwnedValue], _lang: &str) -> Result<Vec<OwnedValue>> {
    let mut servers: Vec<String> = arg_to_array(args, 0);
    let searchdomain = arg_to_string(args, 1, "").unwrap_or_default();

    let user_servers = read_nameservers(RESOLV_USER);
    let luppo_servers = read_nameservers(RESOLV_LUPUS);

    servers.extend(user_servers);
    servers.extend(luppo_servers);
    servers.sort();
    servers.dedup();

    let mut content = String::from(
        "# This file is automatically generated by COMAR\n\
         # Use network-manager to set default DNS settings\n\
         #\n",
    );
    for s in servers.iter().take(MAX_SERVERS) {
        content.push_str(&format!("nameserver {}\n", s));
    }
    if let Some(sd) = resolve_searchdomain(searchdomain) {
        content.push_str(&format!("search {}\n", sd));
    }
    std::fs::write("/etc/resolv.conf", content.as_bytes())
        .map_err(|e| ComarError::Io(e))?;
    Ok(vec![])
}

fn register_name_servers(args: &[OwnedValue], lang: &str) -> Result<Vec<OwnedValue>> {
    let servers: Vec<String> = arg_to_array(args, 1);
    let searchdomain = arg_to_string(args, 2, "").unwrap_or_default();
    use_name_servers_inner(&servers, &searchdomain, lang)
}

fn unregister_name_servers(args: &[OwnedValue], lang: &str) -> Result<Vec<OwnedValue>> {
    let _iface = arg_to_string(args, 0, "").unwrap_or_default();
    let _old_servers: Vec<String> = arg_to_array(args, 1);

    let mut servers = read_nameservers(RESOLV_USER);
    servers.retain(|s| !_old_servers.contains(s));

    let current_domain = get_search_domain_from_file();
    let searchdomain = if current_domain == arg_to_string(args, 2, "").unwrap_or_default() {
        String::new()
    } else {
        current_domain
    };

    use_name_servers_inner(&servers, &searchdomain, lang)
}

fn use_name_servers_inner(
    servers: &[String],
    searchdomain: &str,
    _lang: &str,
) -> Result<Vec<OwnedValue>> {
    let mut combined: Vec<String> = servers.to_vec();
    combined.extend(read_nameservers(RESOLV_USER));
    combined.extend(read_nameservers(RESOLV_LUPUS));
    combined.sort();
    combined.dedup();

    let mut content = String::from(
        "# This file is automatically generated by COMAR\n\
         # Use network-manager to set default DNS settings\n\
         #\n",
    );
    for s in combined.iter().take(MAX_SERVERS) {
        content.push_str(&format!("nameserver {}\n", s));
    }
    resolve_searchdomain(searchdomain.to_string()).map(|sd| {
        content.push_str(&format!("search {}\n", sd));
    });
    std::fs::write("/etc/resolv.conf", content.as_bytes())
        .map_err(|e| ComarError::Io(e))?;
    Ok(vec![])
}

fn read_nameservers(path: &str) -> Vec<String> {
    let content = match std::fs::read_to_string(path) {
        Ok(c) => c,
        Err(_) => return vec![],
    };
    content
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            if line.starts_with("nameserver") {
                line.split_whitespace().nth(1).map(|s| s.to_string())
            } else {
                None
            }
        })
        .collect()
}

fn get_search_domain_from_file() -> String {
    let content = match std::fs::read_to_string(RESOLV_USER) {
        Ok(c) => c,
        Err(_) => return String::new(),
    };
    content
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            if line.starts_with("search") || line.starts_with("searchdomain") {
                line.split_whitespace().nth(1).map(|s| s.to_string())
            } else {
                None
            }
        })
        .next()
        .unwrap_or_default()
}

fn resolve_searchdomain(searchdomain: String) -> Option<String> {
    if !searchdomain.is_empty() {
        return Some(searchdomain);
    }
    let dom = get_search_domain_from_file();
    if !dom.is_empty() { Some(dom) } else { None }
}

fn arg_to_string(args: &[OwnedValue], idx: usize, _default: &str) -> Result<String> {
    args.get(idx)
        .and_then(|v| {
            use std::ops::Deref;
            match v.deref() {
                Value::Str(s) => Some(s.as_str().to_string()),
                _ => None,
            }
        })
        .ok_or_else(|| ComarError::Invalid(format!("Missing string argument at index {}", idx)))
}

fn arg_to_array(args: &[OwnedValue], idx: usize) -> Vec<String> {
    args.get(idx)
        .and_then(|v| {
            use std::ops::Deref;
            match v.deref() {
                Value::Array(arr) => Some(
                    arr.iter()
                        .filter_map(|e| match e {
                            Value::Str(s) => Some(s.as_str().to_string()),
                            _ => None,
                        })
                        .collect(),
                ),
                _ => None,
            }
        })
        .unwrap_or_default()
}
